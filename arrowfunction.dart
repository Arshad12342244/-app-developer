int multiply(a, b) => a * b;
int square(int a) => a * a;
int subtract(int a, int b) => a - b;
int Add(a, b) => a + b;
int divide(a, b) => a ~/ b;
void main() {
  print("the result of multiplying 4 and2 s :${multiply(4, 3)}");
  print("the result of square 4 and2 s :${square(4)}");
  print("the result of subtract 4 and2 s :${subtract(4, 3)}");
  print("the result of add 4 and2 s :${Add(4, 3)}");
  print("the result of divide 4 and2 s :${divide(4, 3)}");
}
